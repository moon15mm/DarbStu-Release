def _load_overrides() -> dict:
    """قائمة المدرسة — تُنشأ عند الغياب وتَعلو على المدمجة."""
    try:
        if os.path.exists(GENDER_NAMES_JSON):
            with open(GENDER_NAMES_JSON, encoding="utf-8") as f:
                d = json.load(f)
            if isinstance(d, dict):
                return d
    except Exception as e:
        print(f"[GENDER] تعذّرت قراءة قائمة الأسماء: {e}")
    return {}


def _save_overrides(d: dict):
    try:
        os.makedirs(DATA_DIR, exist_ok=True)
        tmp = GENDER_NAMES_JSON + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=2)
        os.replace(tmp, GENDER_NAMES_JSON)
    except Exception as e:
        print(f"[GENDER] تعذّر الحفظ: {e}")


def _norm(name: str) -> str:
    """يوحّد صيغة الاسم — الهمزات والتاء المربوطة تختلف بين السجلات."""
    s = (name or "").strip()
    for a, b in (("أ", "ا"), ("إ", "ا"), ("آ", "ا"), ("ٱ", "ا"),
                 ("ة", "ه"), ("ى", "ي")):
        s = s.replace(a, b)
    return s


_MALE_N = {_norm(x) for x in _MALE}
_FEMALE_N = {_norm(x) for x in _FEMALE}
_MALE_EXC_N = {_norm(x) for x in _MALE_EXCEPTIONS}


def guess_gender(full_name: str, overrides=None) -> str:
    """
    يُرجع male / female / unknown من الاسم الأول.

    الترتيب مقصود: قائمة المدرسة، ثم المدمجة، ثم استثناءات الذكور،
    ثم اللاحقة. عكسُه يجعل «حمزة» بنتاً و«سلمى» ولداً.
    """
    first = (full_name or "").strip().split()
    if not first:
        return UNKNOWN
    raw = first[0]
    n = _norm(raw)
    if not n:
        return UNKNOWN

    ov = _load_overrides() if overrides is None else overrides
    for key in (raw, n):
        v = str(ov.get(key, "")).strip().lower()
        if v in (MALE, FEMALE):
            return v

    if n in _MALE_EXC_N:
        return MALE
    if n in _MALE_N:
        return MALE
    if n in _FEMALE_N:
        return FEMALE
    # اللاحقة أخيراً — بعد أن استُبعد الذكور المنتهون بها
    if n.endswith("ه") or n.endswith("اء"):
        return FEMALE
    return UNKNOWN


def classify_names(names):
    """
    يصنّف قائمة أسماء ويُرجع (خريطة, المجهولة).

    المجهولة تُكتب في `gender_names.json` بقيمة فارغة ليملأها من يعرف
    الأسماء — فيتعلّم النظام أسماء كل مدرسة بمرور الوقت بدل أن يُخمّن.
    """
    ov = _load_overrides()
    out, unknown = {}, []
    for nm in names:
        g = guess_gender(nm, overrides=ov)
        out[nm] = g
        if g == UNKNOWN:
            f = (nm or "").strip().split()
            if f and f[0] not in unknown:
                unknown.append(f[0])
    if unknown:
        for u in unknown:
            ov.setdefault(u, "")
        _save_overrides(ov)
        print(f"[GENDER] {len(unknown)} اسماً يحتاج تحديد الجنس في "
              f"{GENDER_NAMES_JSON}")
    return out, unknown
